// A patch release that moves the mod API would change docs that players
// on the earlier patch still read, so the sync stops unless forced.
func TestSyncStopsWhenTheModAPIChanges(t *testing.T) {
	content := t.TempDir()
	if _, err := sync(guide(), content, "0.14", "", false); err != nil {
		t.Fatal(err)
	}
	g := guide()
	g["modding/sharing.md"] = &fstest.MapFile{Data: []byte("# Sharing a mod\n\n- `api`: This Bururu speaks `\"0.13\"`.\n")}
	_, err := sync(g, content, "0.14", "", false)
	if err == nil || !strings.Contains(err.Error(), "the 0.14 docs are for mod API 0.12, and this guide is for 0.13") {
		t.Fatalf("err = %v, want one about the mod API", err)
	}
	if _, err := os.Stat(filepath.Join(content, "0.14", "en", "rules.md")); err != nil {
		t.Errorf("the refused sync changed the pages: %v", err)
	}
	if _, err := sync(g, content, "0.14", "", true); err != nil {
		t.Fatal(err)
	}
	var vf versionsFile
	b, _ := os.ReadFile(filepath.Join(content, "versions.json"))
	json.Unmarshal(b, &vf)
	if vf.Versions[0].API != "0.13" {
		t.Errorf("after -force: versions = %+v", vf.Versions)
	}
}

